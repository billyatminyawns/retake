#!/usr/bin/env bash
# deploy/pages-publish.sh — publish the Retake UI to GitHub Pages (idempotent; safe to re-run).
#
#   API_BASE=https://retake-api.example.com deploy/pages-publish.sh
#   → https://billyatminyawns.github.io/retake/
#
# Every run:
#   1. copies ui/ → docs/ and writes docs/config.js so the hosted UI talks to $API_BASE
#   2. git-inits the project on first run, keeps .venv / var / keys out via .gitignore
#   3. commits, creates the public GitHub repo if it is missing (gh), pushes main
#   4. enables GitHub Pages from main:/docs through the REST API (create or update)
#   5. requests a Pages build and prints the URL
#
# Env:  API_BASE    public origin of the API (required; falls back to deploy/.tunnel-url
#                   written by deploy/tunnel.sh). No trailing slash, no /v1.
#       REPO        owner/name (default billyatminyawns/retake)
#       PAGES_ONLY  1 = commit only docs/ README.md .gitignore (default 0 = whole project source)
#       COMMIT_MSG  custom commit message
# Needs: gh authenticated as the repo owner (`gh auth status`), git ≥ 2.23.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="${REPO:-billyatminyawns/retake}"
PAGES_ONLY="${PAGES_ONLY:-0}"
API_BASE="${API_BASE:-}"

say() { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

if [[ -z "$API_BASE" && -s "$ROOT/deploy/.tunnel-url" ]]; then
  API_BASE="$(head -n1 "$ROOT/deploy/.tunnel-url")"
  say "API_BASE not set — using deploy/.tunnel-url: $API_BASE"
fi
[[ -n "$API_BASE" ]] || die "set API_BASE to the public origin of the API (e.g. https://xxxx.trycloudflare.com or https://owner-retake.hf.space)"
API_BASE="${API_BASE%/}"
[[ "$API_BASE" =~ ^https?://[^/]+ ]] || die "API_BASE must look like https://host[:port] (got: $API_BASE)"
if [[ "${API_BASE#*://}" == */* ]]; then
  echo "warning: API_BASE has a path component; the UI appends /v1/... to the ORIGIN" >&2
fi
command -v gh  >/dev/null || die "gh is not installed (brew install gh)"
command -v git >/dev/null || die "git is not installed"
gh auth status >/dev/null 2>&1 || die "gh is not authenticated — run: gh auth login"
[[ -f "$ROOT/ui/index.html" ]] || die "ui/index.html not found under $ROOT"

cd "$ROOT"

# 1. docs/ = ui/ + generated config.js --------------------------------------------------
say "Building docs/ from ui/ (API_BASE=$API_BASE)"
rm -rf docs
mkdir -p docs
cp -R ui/. docs/
cat > docs/config.js <<EOF
/* Generated by deploy/pages-publish.sh — do not edit; edit ui/config.js and re-run the script.
   The hosted UI talks to this API origin. A value saved in the Settings drawer overrides it. */
window.RETAKE_API_BASE = "$API_BASE";
EOF
touch docs/.nojekyll
find docs -name '.DS_Store' -delete 2>/dev/null || true

# 2. git repo + .gitignore --------------------------------------------------------------
if [[ ! -d .git ]]; then
  say "Initialising git repository (branch main)"
  git init -q
  git symbolic-ref HEAD refs/heads/main
fi
ensure_ignore() { grep -qxF -- "$1" .gitignore 2>/dev/null || printf '%s\n' "$1" >> .gitignore; }
for p in .venv/ var/ cache/ out/ models/ data/runtime/ __pycache__/ '*.pyc' .env deploy/.env \
         deploy/.tunnel-url .DS_Store node_modules/ '*.part' '*.part.wav' .pytest_cache/; do
  ensure_ignore "$p"
done

current="$(git symbolic-ref --short -q HEAD || true)"
if [[ "$current" != "main" ]]; then
  if git show-ref --verify --quiet refs/heads/main; then git checkout -q main; else git branch -m main; fi
fi

if ! git config user.email >/dev/null; then
  login="$(gh api user --jq .login)"
  git config user.name "$login"
  git config user.email "${login}@users.noreply.github.com"
fi

if [[ "$PAGES_ONLY" == "1" ]]; then
  git add -A -- docs .gitignore
  [[ -f README.md ]] && git add -- README.md
else
  git add -A
fi

# The repo is PUBLIC: refuse to commit anything that looks like an API key.
if git diff --cached -U0 | grep -qE '^\+.*(sk-ant-[A-Za-z0-9_-]{16,}|(WELLSAID|ANTHROPIC|RETAKE)_API_KEYS?=[A-Za-z0-9_-]{12,})'; then
  git diff --cached --name-only | sed 's/^/    /' >&2
  die "staged content contains what looks like an API key — remove it or .gitignore the file, then re-run"
fi

# GitHub hard-rejects files > 100 MB; catch it before the push fails half-way.
while IFS= read -r -d '' f; do
  [[ -f "$f" ]] || continue
  sz="$(stat -f %z "$f" 2>/dev/null || stat -c %s "$f")"
  if (( sz > 95 * 1024 * 1024 )); then
    die "$f is $(( sz / 1024 / 1024 )) MB — GitHub rejects files over 100 MB. Add it to .gitignore and re-run."
  fi
done < <(git diff --cached --name-only -z --diff-filter=AM)

if git diff --cached --quiet; then
  say "Nothing new to commit"
else
  say "Committing $(git diff --cached --name-only | wc -l | tr -d ' ') file(s) ($([[ "$PAGES_ONLY" == "1" ]] && echo "docs/ + README only" || echo "whole project source; PAGES_ONLY=1 for docs/ only"))"
  git commit -q -m "${COMMIT_MSG:-Publish UI to GitHub Pages (API_BASE=$API_BASE)}"
  say "Committed $(git rev-parse --short HEAD)"
fi

# 3. GitHub repo + push -----------------------------------------------------------------
if gh repo view "$REPO" >/dev/null 2>&1; then
  say "GitHub repo $REPO exists"
else
  say "Creating public GitHub repo $REPO"
  gh repo create "$REPO" --public \
     --description "Retake — pronunciation QA for AI voiceover (hosted UI + API)" >/dev/null
fi
remote_url="https://github.com/$REPO.git"
if git remote get-url origin >/dev/null 2>&1; then
  cur="$(git remote get-url origin)"
  case "$cur" in
    "$remote_url"|"https://github.com/$REPO"|"git@github.com:$REPO.git"|"git@github.com:$REPO") ;;
    *) echo "warning: origin was $cur — repointing at $remote_url" >&2; git remote set-url origin "$remote_url" ;;
  esac
else
  git remote add origin "$remote_url"
fi

# Per-invocation credential helper: gh's token, no change to global git config.
GIT_CRED=(-c "credential.https://github.com.helper=" -c "credential.https://github.com.helper=!gh auth git-credential")
say "Pushing main → $REPO"
if ! git "${GIT_CRED[@]}" push -q -u origin main 2>/dev/null; then
  say "Push rejected — rebasing onto origin/main first"
  git "${GIT_CRED[@]}" pull -q --rebase --autostash origin main || die "could not reconcile with origin/main; resolve and re-run"
  git "${GIT_CRED[@]}" push -q -u origin main
fi

# 4. GitHub Pages from main:/docs (create or update) ------------------------------------
say "Enabling GitHub Pages from main:/docs"
pages_body='{"build_type":"legacy","source":{"branch":"main","path":"/docs"}}'
if gh api "repos/$REPO/pages" >/dev/null 2>&1; then
  printf '%s' "$pages_body" | gh api -X PUT  "repos/$REPO/pages" --input - >/dev/null
else
  printf '%s' "$pages_body" | gh api -X POST "repos/$REPO/pages" --input - >/dev/null
fi
gh api -X POST "repos/$REPO/pages/builds" >/dev/null 2>&1 || true   # nudge a build now

# 5. Report -----------------------------------------------------------------------------
url="$(gh api "repos/$REPO/pages" --jq .html_url)"
cat <<EOF

Published.
  UI:    ${url}            (first build ≈ 1 min; hard-refresh after re-publishing)
  Mock:  ${url}?mock=1     (bundled sample job, no API needed)
  API:   $API_BASE
  Repo:  https://github.com/$REPO

The API must allow this origin: RETAKE_CORS_ORIGINS=${url%/}  → origin https://${REPO%%/*}.github.io  (or *).
Re-run with a new API_BASE whenever the API URL changes (quick tunnels change every start),
or just paste the new URL into the UI's Settings drawer.
EOF
